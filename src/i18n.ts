const messages: Record<AppLocale, Record<MessageKey, string>> = {
  'zh-CN': zh,
  'en-US': en,
};

function getSystemLocale(): AppLocale {
  if (typeof navigator === 'undefined') return 'zh-CN';
  const language = navigator.languages?.[0] ?? navigator.language ?? 'zh-CN';
  return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function resolveLocalePreference(preference: LocalePreference): AppLocale {
  return preference === 'system' ? getSystemLocale() : preference;
}

export function getLocale(): AppLocale {
  if (typeof localStorage === 'undefined') return 'zh-CN';
  const raw = localStorage.getItem(LOCALE_KEY);
  if (raw === 'zh-CN' || raw === 'en-US' || raw === 'system') {
    return resolveLocalePreference(raw);
  }
  return getSystemLocale();
}

export function setLocale(locale: LocalePreference): void {
  localStorage.setItem(LOCALE_KEY, locale);
}

export function translate(
  key: MessageKey,
  locale: AppLocale = getLocale(),
  values: Record<string, string | number> = {},
): string {
  const template = messages[locale]?.[key] ?? messages['zh-CN'][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    values[name] === undefined ? `{${name}}` : String(values[name]),
  );
}

export function t(
  key: MessageKey,
  locale: AppLocale = getLocale(),
  values: Record<string, string | number> = {},
): string {
  return translate(key, locale, values);
}

export function useI18n() {
  const locale = useUiStore(state => state.effectiveLocale);
  const preference = useUiStore(state => state.locale);
  const translator = useCallback(
    (key: MessageKey, values?: Record<string, string | number>) => translate(key, locale, values),
    [locale],
  );
  return {
    locale,
    preference,
    t: translator,
  };
}
